function withPrefixIfMissing(
  value: string,
  prefixes: string[],
  defaultPrefix: string
): string {
  const trimmed = value.trim();
  if (!trimmed) return '';
  for (const p of prefixes) {
    if (trimmed.startsWith(p)) {
      return trimmed;
    }
  }
  return `${defaultPrefix}${trimmed}`;
}

/**
 * Formats structured address fields into a clean Khmer full address string:
 * "ភូមិ [Village], ឃុំ/សង្កាត់ [Commune], ស្រុក/ក្រុង [District], ខេត្តបាត់ដំបង"
 */
export function formatFullKhmerAddress(
  parts: Pick<MemberAddress, 'province' | 'district' | 'commune' | 'village'>
): string {
  const segments: string[] = [];

  const village = withPrefixIfMissing(parts.village, ['ភូមិ'], 'ភូមិ ');
  if (village) segments.push(village);

  const commune = withPrefixIfMissing(
    parts.commune,
    ['ឃុំ', 'សង្កាត់'],
    'ឃុំ/សង្កាត់ '
  );
  if (commune) segments.push(commune);

  const district = withPrefixIfMissing(
    parts.district,
    ['ស្រុក', 'ក្រុង', 'ខណ្ឌ'],
    'ស្រុក/ក្រុង '
  );
  if (district) segments.push(district);

  const province = parts.province.trim();
  if (province) segments.push(province);

  return segments.join(', ');
}

